def job(ident, title, prefix, bounds, top=None, back=None, side=None):
    j = dict(id=ident, title=title, concept=str(next(CONCEPT.rglob(prefix+'*.png'))),
             bounds=bounds, top=top, back=back, side=side, parts=[], step=3)
    JOBS.append(j)
