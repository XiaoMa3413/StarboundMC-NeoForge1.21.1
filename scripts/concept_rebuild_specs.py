def poly(j, name, points, depth, center=0, group=None):
    j['parts'].append(dict(name=name, polygon=points, z=[center-depth/2, center+depth/2], group=group or name))


def rect(j, name, x, y, w, h, depth, center=0, group=None):
    poly(j, name, [[x,y],[x+w,y],[x+w,y+h],[x,y+h]], depth, center, group)


def face(j, name, points, depth, thickness=2, group=None):
    for sign in [-1, 1]:
        poly(j, name+('_front' if sign<0 else '_back'), points, thickness, sign*(depth/2+thickness/2), group)


def panel(j, name, x,y,w,h,depth,thickness=2,group=None):
    face(j,name,[[x,y],[x+w,y],[x+w,y+h],[x,y+h]],depth,thickness,group)


